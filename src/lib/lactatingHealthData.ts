import { LactatingHealthRecord } from '../types';
import { calculateLactatingHealthAssessment } from './lactatingHealth';

function createLactatingSeed(params: {
  id: string;
  nik: string;
  fullName: string;
  ageYears: number;
  phone?: string;
  institutionId: string;
  institutionName: string;
  villageOrPosyandu: string;
  babyName: string;
  deliveryDate: string;
  weightKg: number;
  heightCm: number;
  lilaCm: number;
  hemoglobinGdL: number;
  systolicBp: number;
  diastolicBp: number;
  feedingPattern: LactatingHealthRecord['feedingPattern'];
  breastStatus: LactatingHealthRecord['breastStatus'];
  fluidIntakeMl: number;
  vitaminAPostpartum: boolean;
  ttdOrMultivitaminCompliant: boolean;
  measurementDate: string;
  notes?: string;
  recordedBy: string;
}): LactatingHealthRecord {
  const assessment = calculateLactatingHealthAssessment({
    ageYears: params.ageYears,
    deliveryDate: params.deliveryDate,
    measurementDate: params.measurementDate,
    weightKg: params.weightKg,
    heightCm: params.heightCm,
    lilaCm: params.lilaCm,
    hemoglobinGdL: params.hemoglobinGdL,
    systolicBp: params.systolicBp,
    diastolicBp: params.diastolicBp,
    feedingPattern: params.feedingPattern,
    breastStatus: params.breastStatus,
    fluidIntakeMl: params.fluidIntakeMl,
    vitaminAPostpartum: params.vitaminAPostpartum,
    ttdOrMultivitaminCompliant: params.ttdOrMultivitaminCompliant,
  });

  return {
    id: params.id,
    nik: params.nik,
    fullName: params.fullName,
    ageYears: params.ageYears,
    phone: params.phone || '',
    institutionId: params.institutionId,
    institutionName: params.institutionName,
    villageOrPosyandu: params.villageOrPosyandu,
    babyName: params.babyName,
    deliveryDate: params.deliveryDate,
    babyAgeDays: assessment.babyAgeDays,
    lactationWeeks: assessment.lactationWeeks,
    babyAgeMonths: assessment.babyAgeMonths,
    lactationPhase: assessment.lactationPhase,
    feedingPattern: params.feedingPattern,
    breastStatus: params.breastStatus,
    weightKg: params.weightKg,
    heightCm: params.heightCm,
    bmi: assessment.bmi,
    bmiCategory: assessment.bmiCategory,
    lilaCm: assessment.lilaCm,
    isKek: assessment.isKek,
    lilaCategory: assessment.lilaCategory,
    hemoglobinGdL: assessment.hemoglobinGdL,
    anemiaStatus: assessment.anemiaStatus,
    systolicBp: assessment.systolicBp,
    diastolicBp: assessment.diastolicBp,
    bpStatus: assessment.bpStatus,
    fluidIntakeMl: assessment.fluidIntakeMl,
    targetFluidMl: assessment.targetFluidMl,
    isHydrationLow: assessment.isHydrationLow,
    vitaminAPostpartum: params.vitaminAPostpartum,
    ttdOrMultivitaminCompliant: params.ttdOrMultivitaminCompliant,
    recommendedKcal: assessment.recommendedKcal,
    recommendedProteinG: assessment.recommendedProteinG,
    measurementDate: params.measurementDate,
    riskFlags: assessment.riskFlags,
    riskLevel: assessment.riskLevel,
    recommendation: assessment.recommendation,
    notes: params.notes || '',
    recordedBy: params.recordedBy,
    updatedAt: `${params.measurementDate} 09:30`,
  };
}

