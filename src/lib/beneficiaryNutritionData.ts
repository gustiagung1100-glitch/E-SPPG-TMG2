import { BeneficiaryNutritionRecord } from '../types';
import { calculateWHOZScore } from './whoZScore';

function createSeedRecord(input: {
  id: string;
  nik: string;
  fullName: string;
  gender: 'L' | 'P';
  birthDate: string;
  ageMonths: number;
  institutionId: string;
  institutionName: string;
  classOrGroup: string;
  measurementDate: string;
  weightKg: number;
  heightCm: number;
  notes?: string;
  recordedBy: string;
}): BeneficiaryNutritionRecord {
  const z = calculateWHOZScore({
    ageMonths: input.ageMonths,
    gender: input.gender,
    weightKg: input.weightKg,
    heightCm: input.heightCm,
  });

  return {
    id: input.id,
    nik: input.nik,
    fullName: input.fullName,
    gender: input.gender,
    birthDate: input.birthDate,
    ageMonths: input.ageMonths,
    institutionId: input.institutionId,
    institutionName: input.institutionName,
    classOrGroup: input.classOrGroup,
    measurementDate: input.measurementDate,
    weightKg: input.weightKg,
    heightCm: input.heightCm,
    bmi: z.bmi,
    waz: z.waz,
    haz: z.haz,
    whz: z.whz,
    whzIndexLabel: z.whzIndexLabel,
    wazCategory: z.wazCategory,
    hazCategory: z.hazCategory,
    whzCategory: z.whzCategory,
    isStunted: z.isStunted,
    isUnderweight: z.isUnderweight,
    isWasted: z.isWasted,
    isOverweight: z.isOverweight,
    primaryStatus: z.primaryStatus,
    severityLevel: z.severityLevel,
    recommendation: z.recommendation,
    notes: input.notes,
    recordedBy: input.recordedBy,
    updatedAt: `${input.measurementDate} 08:30`,
  };
}

